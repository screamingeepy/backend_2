@dataclass(frozen=True)
class MicrogameSpec:
    spellId: int
    game: Microgame

    def asStruct(self) -> list:
        return [self.spellId, self.spellId, self.game.mechId, self.game.mechLevel,
                self.game.assetIds, list(self.game.sfx)]


@dataclass(frozen=True)
class EnemySpawn:
    itemId: int
    microgames: List[MicrogameSpec] = field(default_factory=list)


def enemy(itemId: int, *verbs: int) -> EnemySpawn:
    games = ENEMY_MICROGAMES[itemId]
    return EnemySpawn(itemId, [MicrogameSpec(verb, games[verb]) for verb in verbs])


def starterEnemy(itemId: int) -> EnemySpawn:
    return enemy(itemId, *FIRST_SPELL_VERBS)


