@dataclass(frozen=True)
class Microgame:
    mechId: int
    primary: int
    secondary: Optional[int] = None
    sfx: tuple = (SFX_CORRECT, SFX_CORRECT)
    mechLevel: int = 1

    @property
    def assetIds(self) -> list:
        if self.secondary is None:
            return [self.primary]
        return [self.primary, self.secondary]


